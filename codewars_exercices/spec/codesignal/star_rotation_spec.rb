require 'codesignal/star_rotation'

describe 'Simple tests' do
  it '#star_rotation' do
    expect(star_rotation([
      [1,0,0,2,0,0,3],
      [0,1,0,2,0,3,0],
      [0,0,1,2,3,0,0],
      [8,8,8,9,4,4,4],
      [0,0,7,6,5,0,0],
      [0,7,0,6,0,5,0],
      [7,0,0,6,0,0,5]], 7, [3,3], 1)).to eq([
        [8,0,0,1,0,0,2],
        [0,8,0,1,0,2,0],
        [0,0,8,1,2,0,0],
        [7,7,7,9,3,3,3],
        [0,0,6,5,4,0,0],
        [0,6,0,5,0,4,0],
        [6,0,0,5,0,0,4]
      ])
    expect(star_rotation([
      [1,0,0,2,0,0,3],
      [0,1,0,2,0,3,0],
      [0,0,1,2,3,0,0],
      [8,8,8,9,4,4,4],
      [0,0,7,6,5,0,0]], 3, [1,5], 81)).to eq([
        [1,0,0,2,0,0,0],
        [0,1,0,2,3,3,3],
        [0,0,1,2,0,0,0],
        [8,8,8,9,4,4,4],
        [0,0,7,6,5,0,0]
      ])
    expect(star_rotation([
      [1,0,0,2,0,0,3],
      [0,1,0,2,0,3,0],
      [0,0,1,2,3,0,0],
      [8,8,8,9,4,4,4],
      [0,0,7,6,5,0,0],
      [0,7,0,6,0,5,0],
      [7,0,0,6,0,0,5]], 3, [3,3], 15)).to eq([
        [1,0,0,2,0,0,3],
        [0,1,0,2,0,3,0],
        [0,0,2,3,4,0,0],
        [8,8,1,9,5,4,4],
        [0,0,8,7,6,0,0],
        [0,7,0,6,0,5,0],
        [7,0,0,6,0,0,5]
      ])
    expect(star_rotation([
      [1,0,3],
      [3,4,5],
      [8,99,0]], 3, [1,1], 4)).to eq([
        [0,99,8],
        [5,4,3],
        [3,0,1]
      ])
    expect(star_rotation([
      [8,16,32],
      [1,0,3],
      [3,4,5],
      [8,99,0],
      [42,56,64]], 3, [2,1], 12)).to eq([
        [8,16,32],
        [0,99,8],
        [5,4,3],
        [3,0,1],
        [42,56,64]
      ])
  end

end
