require 'codesignal/draw_rectangle'

describe 'Simple tests' do
  it '#draw_rectangle' do
    expect(draw_rectangle([
      ["a","a","a","a","a","a","a","a"],
      ["a","a","a","a","a","a","a","a"],
      ["a","a","a","a","a","a","a","a"],
      ["b","b","b","b","b","b","b","b"],
      ["b","b","b","b","b","b","b","b"]], [1,1,4,3])).to eq([
        ["a","a","a","a","a","a","a","a"],
        ["a","*","-","-","*","a","a","a"],
        ["a","|","a","a","|","a","a","a"],
        ["b","*","-","-","*","b","b","b"],
        ["b","b","b","b","b","b","b","b"]
      ])
    expect(draw_rectangle([
      ["a","a","a","a","a","a","a","a"],
      ["a","a","a","a","a","a","a","a"],
      ["a","a","a","a","a","a","a","a"],
      ["b","b","b","b","b","b","b","b"]], [0,0,1,1])).to eq([
        ["*","*","a","a","a","a","a","a"],
        ["*","*","a","a","a","a","a","a"],
        ["a","a","a","a","a","a","a","a"],
        ["b","b","b","b","b","b","b","b"]
      ])
    expect(draw_rectangle([
      ["a","a","a","a","a","a","a","a"],
      ["a","a","a","a","a","a","a","a"],
      ["a","a","a","a","a","a","a","a"],
      ["b","b","b","b","b","b","b","b"]], [0,2,7,3])).to eq([
        ["a","a","a","a","a","a","a","a"],
        ["a","a","a","a","a","a","a","a"],
        ["*","-","-","-","-","-","-","*"],
        ["*","-","-","-","-","-","-","*"]
      ])
    expect(draw_rectangle([
      ["a","a","a"],
      ["a","a","a"],
      ["a","a","a"],
      ["b","b","b"]], [0,0,2,3])).to eq([
        ["*","-","*"],
        ["|","a","|"],
        ["|","a","|"],
        ["*","-","*"]
      ])
    expect(draw_rectangle([
      ["#","#"],
      ["a","a"],
      ["a","a"],
      ["b","b"]], [0,1,1,2])).to eq([
        ["#","#"],
        ["*","*"],
        ["*","*"],
        ["b","b"]
      ])
  end
end
